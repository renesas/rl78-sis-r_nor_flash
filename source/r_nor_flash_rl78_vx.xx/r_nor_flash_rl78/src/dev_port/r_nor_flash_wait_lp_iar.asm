    public    _r_nor_flash_wait_lp

    extern    _g_nor_flash_loop_cnt

;-----------------------------------------------------------------------------
;    r_nor_flash_wait_lp
;-----------------------------------------------------------------------------
    section CODE:CODE

_r_nor_flash_wait_lp:

    MOVW    AX, _g_nor_flash_loop_cnt

    ;--------------------------------------------------
    ; wait loop
    ;--------------------------------------------------
loop:
    SUBW    AX, #1
    BNZ     $loop
    NOP
    NOP

_exit:
    RET
    END
